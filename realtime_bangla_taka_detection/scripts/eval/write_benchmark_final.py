"""Write paper_evidence/BENCHMARK_FINAL.md: the JaalTaka leaderboard, read from saved test files.

Same note-disjoint split (974 / 208 / 208, seed 42), same 208 test notes, first-k views.
Section A: methods with test files for all three training seeds (42, 43, 44): mean ± sample std.
Section B: deterministic frozen-backbone probes (no training seed).
Section C: seed-42-only variants. They are best-of-many rows on a reused test split
           (NEW_TEST_SET.md) and are listed for completeness, not ranked.
Nothing is imputed: a missing file leaves a gap.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
R = ROOT / "results"
OUT = ROOT.parent / "paper_evidence" / "BENCHMARK_FINAL.md"
SEEDS = (42, 43, 44)
KS = range(1, 7)


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def per_k_dirs(d: Path) -> dict[int, float] | None:
    out = {}
    for k in KS:
        m = load(d / f"{k}view" / "test_metrics.json")
        if m is None:
            return None
        out[k] = m["accuracy"]
    return out


def per_k_views(p: Path) -> dict[int, float] | None:
    m = load(p)
    if m is None:
        return None
    rows = m.get("views") or m.get("proposed")
    return {int(r["k"]): r["accuracy"] for r in rows} if rows else None


def camva(which: str, s: int) -> dict[int, float] | None:
    m = load(R / "camva" / "multiseed" / f"seed{s}.json")
    return {int(v["n_views"]): v[f"{which}_accuracy"] for v in m["views"]} if m else None


def late(s: int, key: str) -> dict[int, float] | None:
    m = load(R / "sota" / f"late_fusion_seed{s}.json")
    return {int(k): v for k, v in m[key].items()} if m else None


THREE_SEED = {
    "CNN+ViT baseline (CAMVA repo)": lambda s: camva("baseline", s),
    "CAMVA quality attention": lambda s: camva("camva", s),
    "PRMVT stage 1 (prefix, 6 epochs)": lambda s: per_k_dirs(R / f"qduig/prefix/seed{s}/test_views_20260928"),
    "PRMVT (prefix + fine-tune)": lambda s: per_k_dirs(R / f"qduig/prefix_ft/seed{s}/test_views_20260928"),
    "Same network, fixed 6-view, per-count BN": lambda s: per_k_dirs(R / f"same_arch/fixed/s2/seed{s}/test_views"),
    "Same network, fixed 6-view, shared BN": lambda s: per_k_dirs(R / f"same_arch/fixed_shbn/s2/seed{s}/test_views"),
    "Same network, prefix, shared BN": lambda s: per_k_dirs(R / f"same_arch/prefix_shbn/s2/seed{s}/test_views"),
    "PRMVT checkpoints, score-level late fusion": lambda s: late(s, "late_fusion_mean_prob"),
    "CVS": lambda s: per_k_views(R / f"novel_v2/cvs/seed{s}/test/test_metrics.json"),
    "NDAL": lambda s: per_k_views(R / f"novel_v2/ndal/seed{s}/test/test_metrics.json"),
    "PRAVT": lambda s: per_k_views(R / f"novel_v2/pravt/seed{s}/test/test_metrics.json"),
    "VAT": lambda s: per_k_views(R / f"novel_v2/vat/seed{s}/test/test_metrics.json"),
    # seeds 43 and 44 added 2026-09-29 (scripts/train/run_extra_seeds.py)
    "MTPT (6+3, selected on VAL 1-view)": lambda s: per_k_views(R / f"novel_v2/mtpt_prefix_ft/seed{s}/test/test_metrics.json"),
    "VCIE (k1 fine-tune)": lambda s: per_k_views(R / f"novel_v2/vcie_k1/seed{s}/test/test_metrics.json"),
    "APC": lambda s: per_k_views(R / f"novel_v2/apc/seed{s}/test/test_metrics.json"),
    "CRIS": lambda s: per_k_views(R / f"novel_v2/cris/seed{s}/test/test_metrics.json"),
    "MAVT": lambda s: per_k_views(R / f"novel_v2/mavt/seed{s}/test/test_metrics.json"),
    "SAVS": lambda s: per_k_views(R / f"novel_v2/savs/seed{s}/test/test_metrics.json"),
}


def cell(vals: list[float]) -> str:
    a = np.asarray(vals) * 100
    return f"{a.mean():.1f} ± {a.std(ddof=1):.1f}"


def main() -> None:
    L = ["# JaalTaka benchmark leaderboard (final, 2026-09-29)", "",
         "Generated by `realtime_bangla_taka_detection/scripts/eval/write_benchmark_final.py` from saved test files. "
         "Split: note-disjoint 974 / 208 / 208 (seed 42). Test: 208 notes (120 genuine, 88 counterfeit). "
         "Accuracy on the first k views, threshold 0.5. Checkpoints and thresholds were chosen on validation.", "",
         "## A. Methods with all three training seeds (mean ± sample std, %)", "",
         "| method | " + " | ".join(f"k={k}" for k in KS) + " | mean over k |", "|---|" + "---:|" * 7]
    ranked = []
    missing = []
    for name, fn in THREE_SEED.items():
        runs = [fn(s) for s in SEEDS]
        if any(r is None for r in runs):
            missing.append(f"{name}: seeds {[s for s, r in zip(SEEDS, runs) if r is None]}")
            continue
        per_k = [[r[k] for r in runs] for k in KS]
        ranked.append((np.mean([np.mean(v) for v in per_k]), name, per_k))
    for mean_all, name, per_k in sorted(ranked, reverse=True):
        L.append(f"| {name} | " + " | ".join(cell(v) for v in per_k) + f" | {mean_all * 100:.1f} |")
    if missing:
        L += ["", "Incomplete (not ranked): " + "; ".join(missing)]

    L += ["", "## B. Frozen ImageNet backbones, linear probe (deterministic, %)", ""]
    pr = load(R / "sota" / "backbone_probes.json")
    if pr:
        L += ["One logistic regression on single TRAIN views, C chosen on VAL, k views = mean probability "
              "(`scripts/eval/eval_backbone_probes.py`). No training seed; features are fixed.", "",
              "| backbone | " + " | ".join(f"k={k}" for k in KS) + " | mean over k |", "|---|" + "---:|" * 7]
        for name, r in sorted(pr.items(), key=lambda kv: -np.mean(list(kv[1]["test_acc"].values()))):
            v = [r["test_acc"][str(k)] for k in KS]
            L.append(f"| {name} | " + " | ".join(f"{x * 100:.1f}" for x in v) + f" | {np.mean(v) * 100:.1f} |")
    else:
        L.append("`results/sota/backbone_probes.json` not present: NOT_MEASURED.")

    L += ["", "## C. Seed-42-only variants (not ranked)", "",
          "About 110 runs have scored the same 208 test notes (`NEW_TEST_SET.md`). A single-seed maximum among them is "
          "optimistic by up to about 3 points, so these rows are listed, not ranked.", "",
          "| run | k=1 | k=6 | file |", "|---|---:|---:|---|"]
    single = []
    for d in sorted((R / "novel_v2").iterdir()) + sorted((R / "novel").iterdir()):
        if not (d / "seed42" / "test" / "test_metrics.json").is_file() or (d / "seed43").is_dir():
            continue
        v = per_k_views(d / "seed42" / "test" / "test_metrics.json")
        if v and 1 in v and 6 in v:
            single.append((d.relative_to(R).as_posix(), v[1], v[6]))
    for sub in ("ablation_prefix", "ablations"):
        for d in sorted((R / "qduig" / sub).iterdir()):
            v = per_k_dirs(d / "seed42" / "test_views_20260928")
            if v:
                single.append((d.relative_to(R).as_posix(), v[1], v[6]))
    for name, a1, a6 in single:
        L.append(f"| {name} | {a1 * 100:.1f} | {a6 * 100:.1f} | `results/{name}` |")
    L += ["", f"{len(ranked)} three-seed methods, {len(pr or {})} probes, {len(single)} single-seed rows.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("WROTE", OUT, len(ranked), len(single))


if __name__ == "__main__":
    main()
