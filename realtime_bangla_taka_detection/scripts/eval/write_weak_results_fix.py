"""Write paper_evidence/WEAK_RESULTS_FIX.md from the saved result files.

Every number is read from a JSON file written by an evaluation script:
  results/qduig/eval/seed42/policies/all_policies.json          old policy results
  results/qduig/eval_<run>/seed<N>/policies/all_policies.json    re-run after the fixes
  results/qduig/reeval_20260928.json                             1-6 view re-evaluation
  results/camva/multiseed/summary.json                           CAMVA over seeds
Missing files are reported as NOT_MEASURED.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
Q = ROOT / "results" / "qduig"
OUT = ROOT.parent / "paper_evidence" / "WEAK_RESULTS_FIX.md"
POLICIES = ["fixed_order", "random", "quality_only", "confidence_only", "diversity_only",
            "quality_diversity", "uncertainty_quality", "uncertainty_diversity", "full_proposed"]
KS = [1, 2, 3, 4, 5, 6, "adaptive"]


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def policy_table(rows: list[dict]) -> dict:
    t = {}
    for r in rows:
        t[(r["policy"], r["n_views_requested"])] = (r["accuracy"], r.get("average_views"))
    return t


def pct(x) -> str:
    return "NOT_MEASURED" if x is None else f"{100 * x:.1f}"


def main() -> None:
    lines = ["# Weak results: causes and fixes (2026-09-28)", "",
             "Generated by `realtime_bangla_taka_detection/scripts/eval/write_weak_results_fix.py`. "
             "Every number is read from a saved result file; see the script header for the paths.", ""]

    lines += ["## Summary", "",
              "- Most of the collapsed policy results were caused by evaluation bugs, not by the methods. After "
              "the fixes no policy collapses on either model (tables below).",
              "- On the deployed prefix_ft model the plain fixed view order is the best (or tied best) policy at every view "
              "count. The learned policies (quality, confidence, diversity, CRIQP `full_proposed`) pick a weaker "
              "first view and do worse at 1-4 views; `full_proposed` with adaptive stopping stops after one view "
              "below fixed order. Learned view selection is a negative result, not a working method.",
              "- The NaN bug also changed stored 1-6 view numbers. Several variants reported as degrading with "
              "more views (`rsqa`, `her_base`, `auxfix_stopgrad`, `auxfix_separate*`) do not degrade once it is "
              "fixed. Documents whose verdicts used those numbers carry a correction note.",
              "- The early Q-DUIG ablations (`results/qduig/ablations`) and the early `proposed` model remain "
              "weak after the fixes. They come from an unstable 4-6 epoch recipe and are superseded by "
              "`results/qduig/ablation_prefix`; they must not be presented as working methods.",
              "- CAMVA's single-seed result holds over three seeds: better than the baseline only at six views, "
              "much worse at one to five.", ""]
    lines += ["## Evaluation bugs that were fixed", "",
              "1. **Sequential policies and the oracle skipped the view self-gate.** `sequential_predict` and "
              "`run_oracle` rebuilt the model from `encode_views`, `_quality` and `fuse_prefix`, but `forward()` "
              "also applies `nan_to_num` and `z * (1 + tanh(view_gate(z)))`. Models trained with "
              "`view_self_gate` (prefix, prefix_ft, the prefix ablations) were scored on features they never saw. "
              "Both now call `QDUIGNet.view_features()`.",
              "2. **NaN for fully confident notes.** `binary_entropy_t` clamped with eps = 1e-8, and in float32 "
              "`1 - 1e-8 == 1.0`, so p = 1 gave `0 * log 0 = NaN`, which reached the HGEF logits. `forward()` "
              "replaced NaN logits with 0 (p = 0.5, read as genuine); the sequential path left them NaN (read as "
              "counterfeit). 23 of 208 test notes were affected for prefix_ft seed 42. eps is now 1e-6.",
              "3. **Masked views changed the volume feature.** `logdet_gram` gave every masked-out view log(tau) "
              "= -4.6, so one selected view inside six slots read -20 instead of about 0. The policies and any "
              "padded batch therefore saw a different context than a plain k-view test loader. Masked views now "
              "contribute log 1 = 0; logits from masked and cut-down inputs agree to 5e-6.",
              "4. **The random policy was not seeded** after its first pick (`torch.rand_like`). It now uses the "
              "seeded generator.",
              "5. **Old Q-DUIG checkpoints no longer loaded** (`view_gate`, `k_bn` added later). They load again "
              "when those layers are switched off in their config.", ""]

    # --- policies
    lines += ["## View-selection policies", ""]
    old = load(Q / "eval" / "seed42" / "policies" / "all_policies.json")
    for run, label in (("proposed", "Early Q-DUIG model (`results/qduig/proposed`, seed 42)"),):
        new = load(Q / f"eval_{run}" / "seed42" / "policies" / "all_policies.json")
        lines += [f"### {label}: before and after the fixes", "",
                  "Accuracy (%) on the 208 test notes. *Before* is `results/qduig/eval/seed42/policies`.", "",
                  "| policy | " + " | ".join(f"{k}v before / after" if k != "adaptive" else "adaptive before / after" for k in KS) + " |",
                  "|---|" + "---:|" * len(KS)]
        to, tn = policy_table(old or []), policy_table(new or [])
        for pol in POLICIES:
            cells = []
            for k in KS:
                a = to.get((pol, k), (None,))[0]
                b = tn.get((pol, k), (None,))[0]
                cells.append(f"{pct(a)} / {pct(b)}")
            lines.append(f"| {pol} | " + " | ".join(cells) + " |")
        lines.append("")

    seeds = [s for s in (42, 43, 44) if (Q / "eval_prefix_ft" / f"seed{s}" / "policies" / "all_policies.json").is_file()]
    lines += ["### Deployed model (`results/qduig/prefix_ft`), after the fixes", ""]
    if not seeds:
        lines += ["NOT_MEASURED", ""]
    else:
        tabs = {s: policy_table(load(Q / "eval_prefix_ft" / f"seed{s}" / "policies" / "all_policies.json")) for s in seeds}
        lines += [f"Mean accuracy (%) over seeds {', '.join(map(str, seeds))}; SD in brackets. "
                  "`adaptive` lets the policy stop early; the number after @ is the mean views used.", "",
                  "| policy | " + " | ".join(f"{k}v" if k != "adaptive" else "adaptive" for k in KS) + " |",
                  "|---|" + "---:|" * len(KS)]
        for pol in POLICIES:
            cells = []
            for k in KS:
                accs = [tabs[s].get((pol, k), (None,))[0] for s in seeds]
                accs = [a for a in accs if a is not None]
                if not accs:
                    cells.append("NOT_MEASURED")
                    continue
                m = 100 * statistics.fmean(accs)
                sd = f" ({100 * statistics.stdev(accs):.1f})" if len(accs) > 1 else ""
                if k == "adaptive":
                    views = statistics.fmean(tabs[s][(pol, k)][1] for s in seeds if (pol, k) in tabs[s])
                    cells.append(f"{m:.1f}{sd} @ {views:.2f}")
                else:
                    cells.append(f"{m:.1f}{sd}")
            lines.append(f"| {pol} | " + " | ".join(cells) + " |")
        lines.append("")

    # --- standard 1-6 view re-evaluation
    re = load(Q / "reeval_20260928.json")
    lines += ["## Standard 1-6 view accuracy, re-evaluated", ""]
    if not re:
        lines += ["NOT_MEASURED", ""]
    else:
        ok = {k: v for k, v in re.items() if v.get("status") == "ok"}
        changed, weak = [], []
        for name, v in sorted(ok.items()):
            new = {int(k): x for k, x in v["new"].items()}
            old_ = {int(k): x for k, x in v["stored"].items()}
            diffs = [new[k] - old_[k] for k in new if old_.get(k) is not None]
            if diffs and max(abs(d) for d in diffs) >= 0.0048:
                changed.append((name, old_, new))
            if min(new.values()) < 0.70:
                weak.append((name, new))
        lines += [f"{len(ok)} checkpoints evaluated with the fixed code; old files in `test_views/` are kept and "
                  "the new ones are in `test_views_20260928/`. Plain k-view loaders never pad, so only bug 2 "
                  "(NaN) can change these numbers.", "",
                  f"### Runs whose accuracy moved by at least one note ({len(changed)})", "",
                  "| run | stored 1-6 views (%) | re-evaluated 1-6 views (%) |", "|---|---|---|"]
        for name, o, n in changed:
            lines.append(f"| {name} | " + " ".join(pct(o.get(k)) for k in range(1, 7)) + " | "
                         + " ".join(pct(n[k]) for k in range(1, 7)) + " |")
        lines += ["", f"### Runs still below 70% at some view count after the fixes ({len(weak)})", "",
                  "These are genuinely weak models, not evaluation errors. They are early or failed training "
                  "variants and must not be presented as working methods.", "",
                  "| run | re-evaluated 1-6 views (%) |", "|---|---|"]
        for name, n in weak:
            lines.append(f"| {name} | " + " ".join(pct(n[k]) for k in range(1, 7)) + " |")
        skipped = {k: v["status"] for k, v in re.items() if v.get("status") != "ok"}
        if skipped:
            lines += ["", "Not evaluated: " + "; ".join(f"`{k}` ({v})" for k, v in skipped.items())]
        lines.append("")

    # --- CAMVA seeds
    cs = load(ROOT / "results" / "camva" / "multiseed" / "summary.json")
    lines += ["## CAMVA over training seeds", ""]
    if not cs or len(cs.get("seeds", [])) < 2:
        lines += ["NOT_MEASURED (fewer than two seeds with both checkpoints).", ""]
    else:
        lines += [f"Seeds {', '.join(map(str, cs['seeds']))}, each CAMVA compared with the baseline of the same seed "
                  f"on {cs['test_notes']} test notes. Accuracy (%), mean (SD). Seed 42 was trained on the RTX 3050; "
                  "CAMVA 43/44 and baseline 43/44 were trained on the laptop CPU on 2026-09-28 with the same "
                  "settings. The earlier baseline seed-43 checkpoint had stopped at epoch 2 (validation 0.899) and "
                  "was retrained; the old file is in `Unused/`.", "",
                  "| views | baseline | CAMVA | CAMVA - baseline | CAMVA better in |", "|---:|---:|---:|---:|---:|"]
        for r in cs["views"]:
            f = lambda m, s: f"{100 * m:.1f} ({100 * s:.1f})" if s is not None else f"{100 * m:.1f}"
            lines.append(f"| {r['n_views']} | {f(r['baseline_mean'], r['baseline_sd'])} | {f(r['camva_mean'], r['camva_sd'])} "
                         f"| {100 * r['difference_mean']:+.1f} | {r['camva_better_in_seeds']}/{r['n_seeds']} seeds |")
        lines.append("")

    # --- calibration and robustness of PRMVT (old files kept in Unused/replaced_originals)
    old_root = ROOT.parent / "Unused" / "replaced_originals" / "realtime_bangla_taka_detection" / "results"
    lines += ["## Calibration and robustness of PRMVT", "",
              "These were measured through `forward()`, which turned the NaN logits into p = 0.5, so they moved "
              "too. *Before* files are kept in `Unused/replaced_originals/`. `ROBUSTNESS_RESULTS.md` (13 "
              "corruptions x 1-6 views) was regenerated by `eval_robustness_top.py`. Its baseline and NDAL "
              "columns shift by one or two notes in places: the old run was on the GPU (TF32 matmuls), the new "
              "one on the CPU; those models use no Q-DUIG code.", ""]
    cal_new = load(ROOT / "results" / "calibration" / "suite_seed42.json")
    cal_old = load(old_root / "calibration" / "suite_seed42.json")
    if cal_new and cal_old:
        lines += ["| PRMVT, 6 views, ECE (10 bins) | before | after |", "|---|---:|---:|"]
        for m in cal_new["prmvt"]["methods"]:
            lines.append(f"| {m} | {cal_old['prmvt']['methods'][m]['ece_10']:.4f} | "
                         f"{cal_new['prmvt']['methods'][m]['ece_10']:.4f} |")
        lines.append("")
    rob = [(r, load(ROOT / "results" / "robustness" / f"{r}_seed42.json"),
            load(ROOT / "results" / "robustness" / f"{r}_seed42_20260928.json")) for r in ("robust_ft", "occlusion_ft")]
    if all(o and n for _, o, n in rob):
        keys = ["clean_1view", "clean_6view", "low_light_0.2_6view", "occlusion_0.55_6view"]
        lines += ["| fine-tuned model | " + " | ".join(f"{k} before / after (%)" for k in keys) + " |",
                  "|---|" + "---:|" * len(keys)]
        for r, o, n in rob:
            lines.append(f"| {r} | " + " | ".join(f"{pct(o[k])} / {pct(n[k])}" for k in keys) + " |")
        lines.append("")
    sev_new = load(ROOT / "results" / "robustness" / "severity_seed42.json")
    sev_old = load(old_root / "robustness" / "severity_seed42.json")
    if sev_new and sev_old and "note" in sev_new:
        old_rows = {(r["corruption"], r["severity"]): r["prmvt"] for r in sev_old["rows"]}
        lines += [f"Severity sweep, PRMVT 6-view accuracy (%). Clean: {pct(sev_old['clean_6view']['prmvt'])} before, "
                  f"{pct(sev_new['clean_6view']['prmvt'])} after. Baseline and NDAL columns are unchanged.", "",
                  "| corruption | severity | before | after |", "|---|---:|---:|---:|"]
        for r in sev_new["rows"]:
            lines.append(f"| {r['corruption']} | {r['severity']:g} | {pct(old_rows[(r['corruption'], r['severity'])])} "
                         f"| {pct(r['prmvt'])} |")
        lines.append("")
    else:
        lines += ["Severity sweep for PRMVT: re-run pending (`scripts/eval/eval_severity_prmvt.py`).", ""]

    lines += ["## Still not measured", "",
              "- **Raspberry Pi 5 latency, temperature and throttling.** Run `savior_glass/scripts/benchmark_pi5.py` "
              "on the Pi (`--sustained 30` for the 30-minute run). It labels any non-Pi host `raspberry_pi_5: false`.",
              "- **User study.** Protocol: `paper_evidence/user_study/study_protocol.md`. After data collection, "
              "`analysis_script.py` runs the paired Wilcoxon tests with Holm correction; with no data it writes "
              "NOT MEASURED.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
