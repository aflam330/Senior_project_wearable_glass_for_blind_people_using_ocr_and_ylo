"""Write paper_evidence/SAME_ARCH_RESULTS.md from saved test files. Does not train.

Reads
  results/same_arch/{fixed,fixed_shbn,prefix_shbn}/s2/seed{42,43,44}/test_views/{k}view/
  results/qduig/prefix_ft/seed{42,43,44}/test_views_20260928/{k}view/   (prefix arm, per-count BN)
  results/qduig/eval/seed42/baseline/baseline_{1,6}view/test_metrics.json (CNN+ViT, seed 42 only)
  results/sota/late_fusion_seed{42,43,44}.json
  results/sota/backbone_probes.json (if present)
Every arm uses the same PRMVT network, the same note-disjoint split and the same 208 test notes.
A missing file is reported as missing; nothing is imputed.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT.parent / "paper_evidence" / "SAME_ARCH_RESULTS.md"
SEEDS = [42, 43, 44]
KS = range(1, 7)
ARMS = {
    "fixed": ("6 views only, per-count BN", "results/same_arch/fixed/s2/seed{s}/test_views"),
    "fixed_shbn": ("6 views only, one shared BN", "results/same_arch/fixed_shbn/s2/seed{s}/test_views"),
    "prefix_shbn": ("prefixes 1-6 + single-view loss, one shared BN", "results/same_arch/prefix_shbn/s2/seed{s}/test_views"),
    "prefix (PRMVT)": ("prefixes 1-6 + single-view loss, per-count BN", "results/qduig/prefix_ft/seed{s}/test_views_20260928"),
}


def rel(p: Path) -> str:
    return p.relative_to(ROOT.parent).as_posix()


def preds(d: Path, k: int) -> tuple[list[str], np.ndarray] | None:
    f = d / f"{k}view" / "test_predictions.json"
    m = d / f"{k}view" / "test_metrics.json"
    if not (f.is_file() and m.is_file()):
        return None
    p = json.loads(f.read_text(encoding="utf-8"))
    y = np.asarray(p["y_true"]) == 1
    correct = (np.asarray(p["genuine_score"]) >= 0.5) == y
    acc = json.loads(m.read_text(encoding="utf-8"))["accuracy"]
    if abs(correct.mean() - acc) > 1e-9:  # threshold-0.5 predictions must reproduce the stored accuracy
        raise SystemExit(f"{f}: recomputed {correct.mean()} != stored {acc}")
    return list(p["note_id"]), correct


def mcnemar_exact(b: int, c: int) -> float:
    """Two-sided exact McNemar p-value from the discordant counts."""
    n = b + c
    if n == 0:
        return 1.0
    tail = sum(math.comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def pct(xs: list[float]) -> str:
    if not xs:
        return "missing"
    a = np.asarray(xs) * 100
    return f"{a.mean():.1f} ± {a.std(ddof=1):.1f}" if len(a) > 1 else f"{a[0]:.1f}"


def main() -> None:
    table: dict[str, dict[int, dict[int, np.ndarray]]] = {}
    ids_ref: list[str] | None = None
    missing = []
    for arm, (_, pat) in ARMS.items():
        table[arm] = {}
        for s in SEEDS:
            d = ROOT / pat.format(s=s)
            table[arm][s] = {}
            for k in KS:
                r = preds(d, k)
                if r is None:
                    missing.append(f"{arm} seed {s} k={k}")
                    continue
                ids, c = r
                if ids_ref is None:
                    ids_ref = ids
                if ids != ids_ref:
                    raise SystemExit(f"note order differs: {d}")
                table[arm][s][k] = c
    n = len(ids_ref or [])

    L = ["# Same-architecture comparison: fixed 6-view training vs prefix training (JaalTaka)", ""]
    L += ["Generated by `realtime_bangla_taka_detection/scripts/eval/write_same_arch_results.py` from saved test files.",
          f"Same PRMVT network, same note-disjoint split, same {n} test notes, seeds 42, 43, 44. "
          "Each run: 6 epochs, then 3 fine-tuning epochs; checkpoint chosen on validation only "
          "(`scripts/train/run_same_arch.py`, `configs/same_arch/`). Test accuracy is the first k views, threshold 0.5.", ""]
    L += ["## Arms", "", "| arm | training | files |", "|---|---|---|"]
    for arm, (desc, pat) in ARMS.items():
        L.append(f"| {arm} | {desc} | `{rel(ROOT / pat.format(s='*'))}` |")
    L += ["", "`prefix_shbn` differs from `fixed_shbn` in two settings at once (mixed view dropout and the 0.5 single-view loss), "
          "so it tests the prefix recipe as a whole, not each setting alone.", ""]

    L += ["## Test accuracy, % (mean ± sample std over the seeds present)", "",
          "| arm | seeds | " + " | ".join(f"k={k}" for k in KS) + " |", "|---|---|" + "---:|" * 6]
    for arm in ARMS:
        seeds_ok = [s for s in SEEDS if len(table[arm][s]) == 6]
        cells = [pct([table[arm][s][k].mean() for s in seeds_ok]) for k in KS]
        L.append(f"| {arm} | {','.join(map(str, seeds_ok)) or 'none'} | " + " | ".join(cells) + " |")

    L += ["", "## Per seed, correct notes out of " + str(n), "",
          "| arm | seed | " + " | ".join(f"k={k}" for k in KS) + " |", "|---|---|" + "---:|" * 6]
    for arm in ARMS:
        for s in SEEDS:
            row = [str(int(table[arm][s][k].sum())) if k in table[arm][s] else "–" for k in KS]
            L.append(f"| {arm} | {s} | " + " | ".join(row) + " |")

    L += ["", "## Paired tests on the same notes (exact McNemar, two-sided)", "",
          "b = notes only the prefix arm gets right, c = notes only the fixed arm gets right.", "",
          "| comparison | seed | k | prefix correct | fixed correct | b | c | p |", "|---|---|---|---:|---:|---:|---:|---:|"]
    for pa, fa in (("prefix (PRMVT)", "fixed"), ("prefix_shbn", "fixed_shbn")):
        for s in SEEDS:
            for k in (1, 6):
                if k in table[pa][s] and k in table[fa][s]:
                    a, b_ = table[pa][s][k], table[fa][s][k]
                    b, c = int((a & ~b_).sum()), int((~a & b_).sum())
                    L.append(f"| {pa} vs {fa} | {s} | {k} | {int(a.sum())} | {int(b_.sum())} | {b} | {c} | {mcnemar_exact(b, c):.3g} |")

    L += ["", "## Baselines on the same test notes", ""]
    base = ROOT / "results/qduig/eval/seed42/baseline"
    bl = {k: base / f"baseline_{k}view/test_metrics.json" for k in (1, 6)}
    if all(p.is_file() for p in bl.values()):
        a1, a6 = (json.loads(bl[k].read_text(encoding="utf-8"))["accuracy"] for k in (1, 6))
        L.append(f"- CNN+ViT (different network), seed 42: {a1 * 100:.1f} % at 1 view, {a6 * 100:.1f} % at 6 views (`{rel(base)}`).")
    lf = [ROOT / f"results/sota/late_fusion_seed{s}.json" for s in SEEDS]
    lf_ok = [json.loads(p.read_text(encoding="utf-8")) for p in lf if p.is_file()]
    if lf_ok:
        L += ["", "Score-level late fusion: the PRMVT network scores each of the first k views alone and the genuine "
              "probabilities are averaged (no training). Compared with PRMVT's own k-view feature fusion, same checkpoints "
              "(`scripts/eval/eval_late_fusion.py`, `results/sota/late_fusion_seed*.json`).", "",
              "| method | seeds | " + " | ".join(f"k={k}" for k in KS) + " |", "|---|---|" + "---:|" * 6]
        seeds = ",".join(str(d["seed"]) for d in lf_ok)
        for key, name in (("late_fusion_mean_prob", "late fusion (mean of per-view probabilities)"),
                          ("prmvt_feature_fusion", "PRMVT feature fusion")):
            L.append(f"| {name} | {seeds} | " + " | ".join(pct([d[key][str(k)] for d in lf_ok]) for k in KS) + " |")
    probes = ROOT / "results/sota/backbone_probes.json"
    L += [""]
    if probes.is_file():
        pr = json.loads(probes.read_text(encoding="utf-8"))
        L += ["Frozen ImageNet backbones used in the JaalTaka data article, as linear probes on this split "
              "(one logistic regression on single train views, C chosen on validation, k views = mean probability; "
              "`scripts/eval/eval_backbone_probes.py`). These are probes, not reproductions of fine-tuned published models.", "",
              "| backbone | feature dim | C | " + " | ".join(f"k={k}" for k in KS) + " |", "|---|---:|---:|" + "---:|" * 6]
        for name, r in pr.items():
            L.append(f"| {name} | {r['feature_dim']} | {r['C_chosen_on_val']} | "
                     + " | ".join(f"{r['test_acc'][str(k)] * 100:.1f}" for k in KS) + " |")
    else:
        L.append("Backbone probes: `results/sota/backbone_probes.json` not present, NOT_MEASURED.")

    L += ["", "## Missing files", "", ("- " + "\n- ".join(missing)) if missing else "None."]
    L += ["", "The same 208 test notes have been scored by many runs in this project (`NEW_TEST_SET.md`). "
          "These arms were fixed before scoring and are reported in full, not selected by test score.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("WROTE", OUT, "missing:", len(missing))


if __name__ == "__main__":
    main()
