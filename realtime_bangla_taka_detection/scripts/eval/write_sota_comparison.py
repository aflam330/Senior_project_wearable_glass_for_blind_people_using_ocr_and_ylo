"""Write paper_evidence/SOTA_COMPARISON.md: same-split comparison with paired tests.

The frozen-backbone probes (eval_backbone_probes.py) saved accuracies only. Here each probe is refit
from its cached TRAIN features with the C it chose on VAL; the refit must reproduce the saved test
accuracy exactly, and then gives per-note predictions for paired (exact McNemar) tests against
PRMVT and the shared-BN prefix network on the same 208 test notes.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from roboeye.camva.notes import load_splits  # noqa: E402

R = ROOT / "results"
OUT = ROOT.parent / "paper_evidence" / "SOTA_COMPARISON.md"
SEEDS = (42, 43, 44)


def mcnemar(a: np.ndarray, b: np.ndarray) -> tuple[int, int, float]:
    n01, n10 = int((a & ~b).sum()), int((~a & b).sum())
    n = n01 + n10
    p = 1.0 if n == 0 else min(1.0, 2 * sum(math.comb(n, i) for i in range(min(n01, n10) + 1)) / 2 ** n)
    return n01, n10, p


def net_correct(d: Path, k: int, ids: list[str]) -> np.ndarray:
    p = json.loads((d / f"{k}view" / "test_predictions.json").read_text(encoding="utf-8"))
    order = {n: i for i, n in enumerate(p["note_id"])}
    y = np.asarray(p["y_true"]) == 1
    c = (np.asarray(p["genuine_score"]) >= 0.5) == y
    return c[[order[n] for n in ids]]


def main() -> None:
    splits, records = load_splits()
    test_ids = list(splits["test"])
    ytest = np.array([int(records[n]["label"]) for n in test_ids])
    probes = json.loads((R / "sota" / "backbone_probes.json").read_text(encoding="utf-8"))
    probe_correct = {}
    for name, r in probes.items():
        f = np.load(R / "sota" / f"feats_{name}.npz", allow_pickle=True)
        pos = {n: i for i, n in enumerate(f["ids"])}
        x = f["x"]
        xtr = x[[pos[n] for n in splits["train"]]].reshape(-1, x.shape[2])
        ytr = np.repeat([int(records[n]["label"]) for n in splits["train"]], 6)
        clf = LogisticRegression(C=r["C_chosen_on_val"], max_iter=3000).fit(xtr, ytr)
        xt = x[[pos[n] for n in test_ids]]
        pr = clf.predict_proba(xt.reshape(-1, x.shape[2]))[:, 1].reshape(len(test_ids), 6)
        probe_correct[name] = {}
        for k in (1, 6):
            c = (pr[:, :k].mean(1) >= 0.5) == (ytest == 1)
            if abs(c.mean() - r["test_acc"][str(k)]) > 1e-9:
                raise SystemExit(f"{name} k={k}: refit {c.mean()} != saved {r['test_acc'][str(k)]}")
            probe_correct[name][k] = c
    nets = {"PRMVT": "qduig/prefix_ft/seed{s}/test_views_20260928",
            "prefix, shared BN": "same_arch/prefix_shbn/s2/seed{s}/test_views"}
    L = ["# Same-split comparison with published backbones (2026-09-29)", "",
         "Generated by `realtime_bangla_taka_detection/scripts/eval/write_sota_comparison.py`. "
         "JaalTaka note-disjoint split, 208 test notes (120 genuine, 88 counterfeit). "
         "The five backbones are the ones evaluated in the JaalTaka data article; its split and numbers were not "
         "available, so they are re-run here as frozen ImageNet features + logistic regression "
         "(C chosen on validation; k views = mean probability). Refit predictions reproduce the saved accuracies exactly.", "",
         "## Accuracy (%)", "", "| system | training seeds | 1 view | 6 views |", "|---|---|---:|---:|"]
    for name, pc in sorted(probe_correct.items(), key=lambda kv: -kv[1][1].mean()):
        L.append(f"| {name}, frozen probe | deterministic | {pc[1].mean() * 100:.1f} | {pc[6].mean() * 100:.1f} |")
    for net, pat in nets.items():
        a1 = [net_correct(R / pat.format(s=s), 1, test_ids).mean() * 100 for s in SEEDS]
        a6 = [net_correct(R / pat.format(s=s), 6, test_ids).mean() * 100 for s in SEEDS]
        L.append(f"| {net} | 42, 43, 44 | {np.mean(a1):.1f} ± {np.std(a1, ddof=1):.1f} | {np.mean(a6):.1f} ± {np.std(a6, ddof=1):.1f} |")
    L += ["", "## Paired tests on the same notes (exact McNemar, two-sided)", "",
          "n01 = notes only the probe gets right; n10 = notes only the network gets right.", "",
          "| probe | network | seed | k | probe correct | network correct | n01 | n10 | p |", "|---|---|---|---|---:|---:|---:|---:|---:|"]
    wins = {"probe": 0, "net": 0, "ns": 0}
    for pname in sorted(probe_correct):
        for net, pat in nets.items():
            for s in SEEDS:
                for k in (1, 6):
                    a = probe_correct[pname][k]
                    b = net_correct(R / pat.format(s=s), k, test_ids)
                    n01, n10, p = mcnemar(a, b)
                    wins["ns" if p >= 0.05 else ("probe" if n01 > n10 else "net")] += 1
                    L.append(f"| {pname} | {net} | {s} | {k} | {int(a.sum())} | {int(b.sum())} | {n01} | {n10} | {p:.3g} |")
    L += ["", f"Of {sum(wins.values())} paired comparisons: probe significantly better {wins['probe']}, "
          f"network significantly better {wins['net']}, no significant difference {wins['ns']} (p ≥ 0.05, uncorrected).", "",
          "## What this means for the paper", "",
          "- Frozen ImageNet features with a per-view linear classifier and score averaging are a strong JaalTaka baseline. "
          "They must appear in any comparison table.",
          "- Such a per-view model has no view-count shift by construction: every view is scored alone. "
          "The view-count collapse and its prefix-training fix (`SAME_ARCH_RESULTS.md`) concern joint multi-view fusion networks, "
          "which is where the paper's claim applies.",
          "- No claim of state of the art on JaalTaka is made. Published numbers on other datasets or splits are listed in `SOTA_BEAT.md` "
          "and are not compared as scores.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("WROTE", OUT, wins)


if __name__ == "__main__":
    main()
