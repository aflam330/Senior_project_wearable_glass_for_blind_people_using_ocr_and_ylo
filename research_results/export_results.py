"""Generate analysis files from research_results/experiments.json (the JSON stays the source of truth).

  python research_results/export_results.py

Writes research_results/exports/
  experiments.csv        wide: one row per experiment, one column per metric            (Excel, SPSS, quick look)
  metrics.csv            long: one row per number, with model / dataset / hardware / seed (pandas, R, plotting)
  comparisons.csv        per comparison group and variant: n runs, mean, sd, min, max    (tables, bar charts with error bars)
  claims.csv             publication claims and the experiments that support them
  comparison_tables.md   ready-to-paste tables, one per comparison group and dataset split

sd is written only where two or more runs exist. Failed and planned experiments are listed in experiments.csv
(they carry no numbers) and never enter a mean.
"""
from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from research_results import results_db as DB  # noqa: E402

PCT = ("accuracy", "cer", "wer", "precision", "recall", "f1", "map50", "auc", "exact_match", "rate", "iou")


def fmt(metric, mean, sd, n):
    pct = any(k in metric for k in PCT) and abs(mean) <= 1.5
    if pct:
        s = f"{100 * mean:.1f}" + (f" ± {100 * float(sd):.1f}" if sd != "" else "") + " %"
    else:
        s = f"{mean:.4g}" + (f" ± {float(sd):.3g}" if sd != "" else "")
    return s + (f" (n={n})" if int(n) > 1 else "")


def tables() -> Path:
    rows = list(csv.DictReader(open(DB.EXPORTS / "comparisons.csv", encoding="utf-8-sig")))
    blocks = defaultdict(lambda: defaultdict(dict))
    names = {}
    for r in rows:
        key = (r["comparison_group_id"], r["dataset_name"], r["dataset_split"], r["hardware_device"])
        names[r["comparison_group_id"]] = r["comparison_group"]
        blocks[key][r["variant"]][f"{r['kind']}.{r['metric']}"] = (float(r["mean"]), r["sd"], r["n_runs"])
    out = ["# Comparison tables", "",
           "Generated by `research_results/export_results.py` from `experiments.json`. Do not edit; regenerate instead.",
           "Mean ± sd over the stored runs; sd appears only where two or more runs exist.", ""]
    last = None
    for (gid, ds, split, hw), variants in sorted(blocks.items(), key=lambda x: [str(v) for v in x[0]]):
        metrics = [m for m in sorted({m for v in variants.values() for m in v}) if sum(m in v for v in variants.values()) >= max(1, len(variants) // 2)]
        metrics = [m for m in metrics if not m.endswith("_n") and "per_class" not in m][:9]
        if not metrics:
            continue
        if gid != last:
            out += [f"## {gid}: {names.get(gid, '')}", ""]
            last = gid
        out += [f"**Dataset:** {ds or '—'} · **Split:** {split or '—'} · **Hardware:** {hw or '—'}", "",
                "| Variant | " + " | ".join(m.split(".", 1)[1] for m in metrics) + " |", "|---|" + "---:|" * len(metrics)]
        for variant, vals in sorted(variants.items()):
            out.append(f"| {variant} | " + " | ".join(fmt(m, *vals[m]) if m in vals else "—" for m in metrics) + " |")
        out.append("")
    path = DB.EXPORTS / "comparison_tables.md"
    path.write_text("\n".join(out), encoding="utf-8")
    return path


def main() -> None:
    probs = DB.validate(DB.load())
    for p in probs:
        print("PROBLEM", p)
    print("export:", DB.export())
    print("tables:", DB.rel(tables()))
    if probs:
        sys.exit(1)


if __name__ == "__main__":
    main()
