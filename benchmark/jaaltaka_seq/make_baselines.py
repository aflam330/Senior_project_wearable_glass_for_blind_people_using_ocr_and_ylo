"""Build split.json, the baseline submissions and the leaderboard from saved project results.

Baselines: the 9 view-selection policies of the project, run on the prefix-robust PRMVT
checkpoints (seeds 42-44) with the fixed evaluation code (2026-09-28), each in its adaptive
(stop-when-confident) setting and forced to 1 and 6 views. Sources:
realtime_bangla_taka_detection/results/qduig/eval_prefix_ft/seed<N>/policies/<policy>_<setting>/test_predictions.json
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

from evaluate import load_split, score

HERE = Path(__file__).resolve().parent
WS = HERE.parents[1]
RBT = WS / "realtime_bangla_taka_detection"
POLICIES = ["fixed_order", "random", "quality_only", "confidence_only", "diversity_only",
            "quality_diversity", "uncertainty_quality", "uncertainty_diversity", "full_proposed"]
SETTINGS = ["adaptive", "1view", "6view"]
SEEDS = [42, 43, 44]


def build_split() -> None:
    sp = RBT / "results" / "camva" / "splits"
    out = {k: json.loads((sp / f"{k}_note_ids.json").read_text(encoding="utf-8")) for k in ("train", "val", "test")}
    for k, v in out.items():
        if isinstance(v, dict):  # tolerate {"note_ids": [...]} layouts
            out[k] = v.get("note_ids") or v.get("ids") or list(v)
    s = {k: set(v) for k, v in out.items()}
    assert not (s["train"] & s["val"] or s["train"] & s["test"] or s["val"] & s["test"]), "split overlap"
    out["meta"] = {"seed": 42, "unit": "physical note", "views_per_note": 6,
                   "sizes": {k: len(v) for k, v in s.items()},
                   "source": "realtime_bangla_taka_detection/results/camva/splits"}
    (HERE / "split.json").write_text(json.dumps(out, indent=1), encoding="utf-8")


def to_submission(pred: dict, name: str, seed: int) -> dict:
    rows = []
    for i, nid in enumerate(pred["note_id"]):
        sel = pred.get("selected_indices")
        used = sel[i] if sel else list(range(int(pred["n_views"][i])))
        rows.append({"note_id": nid, "genuine_prob": float(pred["genuine_score"][i]), "views_used": [int(v) for v in used]})
    return {"name": name, "seed": seed, "predictions": rows}


def main() -> None:
    build_split()
    test_ids = load_split(HERE / "split.json")
    subs_dir = HERE / "baselines"
    subs_dir.mkdir(exist_ok=True)
    results = []
    for pol in POLICIES:
        for setting in SETTINGS:
            per_seed = []
            for seed in SEEDS:
                f = RBT / "results" / "qduig" / "eval_prefix_ft" / f"seed{seed}" / "policies" / f"{pol}_{setting}" / "test_predictions.json"
                if not f.is_file():
                    continue
                sub = to_submission(json.loads(f.read_text(encoding="utf-8")), f"{pol}_{setting}", seed)
                (subs_dir / f"{pol}_{setting}_seed{seed}.json").write_text(json.dumps(sub), encoding="utf-8")
                per_seed.append(score(sub, test_ids))
            if per_seed:
                agg = {"name": f"{pol}_{setting}", "seeds": [r["seed"] for r in per_seed]}
                for m in ("accuracy", "mean_views", "cost_adjusted_accuracy", "wrong_verdict_rate", "ece"):
                    vals = [r[m] for r in per_seed if r[m] is not None]
                    agg[m] = statistics.mean(vals)
                    agg[m + "_sd"] = statistics.stdev(vals) if len(vals) > 1 else 0.0
                results.append(agg)
    results.sort(key=lambda r: -r["cost_adjusted_accuracy"])
    (HERE / "leaderboard.json").write_text(json.dumps(results, indent=1), encoding="utf-8")
    lines = ["# JaalTaka-Seq leaderboard (generated by make_baselines.py)", "",
             "Test split, 208 notes. Mean (SD) over seeds 42-44. Ranked by cost-adjusted accuracy = accuracy - 0.02 x mean views.", "",
             "| rank | policy | accuracy | mean views | cost-adjusted | wrong verdicts | ECE |", "|---:|---|---:|---:|---:|---:|---:|"]
    for i, r in enumerate(results, 1):
        lines.append(f"| {i} | {r['name']} | {r['accuracy']:.4f} ({r['accuracy_sd']:.4f}) | {r['mean_views']:.2f} | "
                     f"{r['cost_adjusted_accuracy']:.4f} | {r['wrong_verdict_rate']:.4f} | {r['ece']:.4f} |")
    (HERE / "LEADERBOARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
